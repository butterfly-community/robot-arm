//! Human-facing explanations. Source details and unresolved differences:
//! README.md; vendor STM32 appendix 2 and web-controller parameter definitions.
pub fn parameter_help(key: &str) -> Option<&'static str> {
    Some(match key {
        "voltage" => "只读，当前供电电压，mV。1000 mV = 1 V；不是电压设定值。",
        "current" => "只读，当前电流，mA。1000 mA = 1 A；反映当时负载，不等于夹持力。",
        "power" => {
            "只读，当前功率，mW。1000 mW = 1 W；不是 0–100 力度百分比，也不是可直接设定的牛顿力。"
        }
        "temperature" => {
            "只读，温度传感器 ADC 原码，不是摄氏度。厂商表中温度升高时 ADC 降低；未确认本型号换算前保留原值。"
        }
        "servo_status" => {
            "只读状态位：bit0 执行中、bit1 指令错误、bit2 堵转、bit3 过压、bit4 欠压、bit5 电流错误、bit6 功率错误、bit7 温度错误；0 表示未置位。"
        }
        "servo_type" => "只读型号编码。没有已核实的编码对照表，不能根据数值推断型号或硬件新旧。",
        "firmware_version" => {
            "只读固件编码，地址 7、两个小端字节。Vxxx 显示规则尚未确认；不是内部参数格式版本，也不根据大小自动切换协议。"
        }
        "serial_number" => "只读序列号原值。本批七个舵机都报告 10000001，不能作为唯一设备身份。",
        "response_switch" => {
            "0：旧 SDK 定义为新运动命令覆盖旧命令、不返回控制完成应答；1：不可中断当前命令，完成后应答，等待队列只有一条。新手册仅描述是否应答，所以不能当成无副作用的日志开关。固定应答的查询不受此开关控制。"
        }
        "servo_id" => {
            "总线寻址 ID：0–254，255 是广播地址。改变后需同步设备映射，并使用新 ID 读取；不改变机械臂关节名称。SDK 支持写入，当前固定映射的机械臂页面只读。"
        }
        "baudrate" => {
            "波特率选项：1=9600、2=19200、3=38400、4=57600、5=115200、6=250000、7=500000、8=1000000。越高传输时间越短，不会直接提高电机速度；写入立即生效，主机和总线设备必须一致。页面只读，SDK 提供写入和主机串口切换。"
        }
        "stall_protect_mode" => {
            "堵转后的处理：0 将功率降至 stall_power_limit；1 释放锁力。不是堵转检测灵敏度，也不是正常工作时的力度指令。"
        }
        "stall_power_limit" => {
            "堵转后的功率上限，mW，配合堵转模式 0。增大允许堵转后维持更高功率，减小降低该功率；不会让正常抓取保持某个力度百分比。"
        }
        "over_volt_low" => {
            "欠压阈值，mV。调高：较高电压就可能触发欠压；调低：允许更低供电电压。不会改变电源实际输出。"
        }
        "over_volt_high" => {
            "过压阈值，mV。调高：容许更高电压；调低：更早触发过压。不会改变电源实际输出。"
        }
        "over_temperature" => {
            "温度保护阈值，ADC 原码，不是 °C。厂商 ADC 表是反向关系：增大 ADC 对应降低温度阈值，减小 ADC 对应升高温度阈值。型号换算未核实，不显示虚构的摄氏度。"
        }
        "over_power" => {
            "功率保护上限，mW。调高允许更高功率，调低更早限功率/触发保护。运动指令 power=0 或超过此值时，厂商定义按此上限执行；它不是恒力目标。"
        }
        "over_current" => {
            "电流保护阈值，mA。调高允许更大电流，调低更早触发电流保护。实际电流由负载、位置控制及电机决定，不是直接设定电流。"
        }
        "accel_switch" => {
            "舵机内部加速度处理开关。旧 SDK 说明只支持 1（梯形加减速），但本机存在实读 0；不同资料不一致，不自动改写。它与每条运动命令的 accel/decel 时间不是同一个参数。"
        }
        "power_hysteresis" => {
            "厂商网页称功率保护迟滞百分比（%），用于保护触发/退出的迟滞。一般增大迟滞会拉大切换间隔、减少反复切换；具体阈值公式、作用方向及范围未公开，不能按猜测计算。旧 SDK 将地址 45 标为保留，新工作台已定义。"
        }
        "po_lock_switch" => {
            "上电时的默认状态：0 释放锁力、1 保持锁力（官方参数表）。修改不等于立即上力/卸力；立即操作使用上力/卸力按钮。旧 C 头文件出现 0x11，不能混同停止指令的保持模式。"
        }
        "angle_limit_switch" => {
            "0 关闭、1 开启舵机内部角度限制；与 angle_limit_high/low 配合。不是 MoveIt/URDF 的关节限制，不能用它推断多圈控制或规划范围已同步改变。"
        }
        "soft_start_switch" => {
            "0 关闭、1 启用上电后的首次角度命令缓慢执行；与 soft_start_time 配合。不是每一段运动的速度倍率。"
        }
        "soft_start_time" => {
            "上电首次执行时间，ms。启用 soft_start_switch 时，增大通常使首次运动更慢，减小更快；不修改后续每条轨迹的运动时间。"
        }
        "angle_limit_high" => {
            "舵机内部角度上限，单位 0.1°（1800=180°）。增大向正方向扩展上限，减小收紧；需要内部限制开关生效。不等于项目 J1–J6 的模型限位。"
        }
        "angle_limit_low" => {
            "舵机内部角度下限，单位 0.1°（-650=-65°）。数值减小向负方向扩展，数值增大收紧；需要内部限制开关生效。不等于项目模型限位。"
        }
        "angle_mid_offset" => {
            "舵机内部中位偏移，单位 0.1°。改变会移动硬件角度参考，不是将关节运动到该角度。不同方向配置下物理正负影响未核实；项目目前不另加软件零偏。"
        }
        "kp" => {
            "位置环比例增益 Kp。按通用 PID 语义：增大通常响应更强、更硬，过大可能振荡；减小通常更柔和，但跟随误差可能增大。厂商未公开系数标度/完整控制律，不保证同数值对应相同力。"
        }
        "kd" => {
            "位置环微分增益 Kd。按通用 PID 语义：增大通常增加动态阻尼、抑制超调，也可能放大测量噪声；减小阻尼作用。厂商未公开内部滤波和标度。"
        }
        "ki" => {
            "位置环积分增益 Ki。按通用 PID 语义：增大可更快消除持续误差，也可能增加超调和积分积累；减小积分作用。厂商积分饱和/清零策略未公开。"
        }
        "bias" => {
            "厂商工作台名称 PwmBias（驱动偏置）。不是角度零偏。偏置如何加到正反向 PWM、是否有死区补偿未公开，不能保证增大就增力或给出具体换算。"
        }
        "hold_kp" => {
            "保持位置时的 Kp。通常增大保持刚性、减小更柔和；过大可能出现抖动。保持模式切换细节未公开。它不是保持 30/50 力度的目标值。"
        }
        "hold_kd" => {
            "保持位置时的 Kd。通常调整保持环阻尼及对动态误差的响应；实际效果取决于固件滤波和负载，不等于降低运动速度。"
        }
        "hold_bias" => {
            "保持模式的 HoldPwmBias。不是关节角度偏移；内部 PWM 偏置计算规则未公开，不能把该值换算成夹持力。"
        }
        "full_deg" => {
            "内部满量程字段，当前仅展示原码。厂商工作台不开放此字段的普通调参，确切标度和修改效果未公开；不用于设置项目的关节角范围。"
        }
        "reserved" => {
            "内部保留字段。读取及写回整个参数块时原样保留，没有可解释的调整用途，不提供单项编辑。"
        }
        "pwm_limit" => {
            "内部 PWM 上限原码，不是 mW 功率上限。与占空比的换算和固件作用方式未公开，只读展示。"
        }
        "direction" => {
            "内部方向字段。与电机方向字段的分工、取值及实际反转作用未公开，只读展示；不能根据名字直接给 J4/J5 加反号。"
        }
        "pwm_frequency" => {
            "内部 PWM 频率编码，不是以 Hz 显示的实值。频率编码映射及调整影响未公开，只读展示。"
        }
        "dead_zone" => {
            "内部死区原码。通常死区影响小误差是否继续驱动，但厂商未公开单位、阈值方向和算法，只读，不自行换算成角度。"
        }
        "motor_direction" => {
            "内部电机方向字段。和 direction 的差异、编码未公开，只读展示；不是应用层关节轴向配置。"
        }
        "version_info" => {
            "内部参数格式/布局版本字段，不是地址 7 的固件版本。读改写时保持原值，不提供单项编辑。"
        }
        _ => return None,
    })
}
